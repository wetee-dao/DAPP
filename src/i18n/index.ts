const i18n = createI18n({
  legacy: false,
  locale: DEFAULT_LOCALE,
  fallbackLocale: LOCALE_EN_US,
  messages
});

export const normalizeLocale = (locale?: string | null) => {
  return locale === LOCALE_ZH_CN ? LOCALE_ZH_CN : LOCALE_EN_US;
};

export const setI18nLanguage = (locale?: string | null) => {
  i18n.global.locale.value = normalizeLocale(locale);
};

export const getRouteLabel = (segment: string) => {
  const key = routeNameMap[segment.toLowerCase()];
  if (!key) {
    return segment;
  }
  return i18n.global.t(key);
};

export default i18n;
